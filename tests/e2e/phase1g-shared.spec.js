import {test,expect} from '@playwright/test';

test('Owner inspects customer master evidence and filters the cross-module explorer',async({page},info)=>{
  test.setTimeout(120000);
  await page.goto('/login');
  await page.locator('#admin-pin').fill(process.env.E2E_ADMIN_PIN||'KmTestOnly123');
  await page.getByRole('button',{name:/^Sign in$/i}).click();
  await expect(page).toHaveURL(/\/admin\/dashboard/);
  const token=await page.evaluate(()=>localStorage.getItem('pos_token'));
  const headers={Authorization:`Bearer ${token}`};
  const suffix=Date.now();
  const response=await page.request.post('/api/admin/customers',{headers,data:{name:`Master ${suffix}`,phone:`97${String(suffix).slice(-8)}`}});
  expect(response.status(),await response.text()).toBe(201);
  const customer=(await response.json()).customer;
  const edited=await page.request.put('/api/admin/customers',{headers,data:{...customer,name:`Corrected ${suffix}`,reason:'Verified customer name'}});
  expect(edited.status(),await edited.text()).toBe(200);
  const evidence=await page.request.get('/api/admin/retail-audit?entity=customer&action=UPDATED',{headers});
  expect(evidence.status(),await evidence.text()).toBe(200);
  const event=(await evidence.json()).events.find(e=>e.entity_id===customer.id);
  expect(event).toBeTruthy();
  await page.goto(`/admin/retail-audit?entity=customer&id=${event.id}`);
  await expect(page.getByRole('heading',{name:'Business Audit',exact:true})).toBeVisible();
  const open=page.getByRole('button',{name:String(customer.id),exact:true});
  await open.focus();await page.keyboard.press('Enter');
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog').getByText(`Corrected ${suffix}`,{exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(open).toBeFocused();
  await page.goto('/admin/retail-transactions?type=goods_receipt');
  await expect(page.getByRole('heading',{name:'Transaction Explorer',exact:true})).toBeVisible();
  await expect(page.locator('tbody tr').first()).toBeVisible();
  await page.locator('tbody tr').first().getByRole('button').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByLabel('Search',{exact:true}).fill('NO-DOCUMENT-MATCH');
  await page.getByRole('button',{name:'Apply filters'}).click();
  await expect(page.getByText('Nothing matches',{exact:true})).toBeVisible();
  await page.goBack();
  await expect(page.locator('tbody tr').first()).toBeVisible();
  await page.getByLabel('Name for the current filters',{exact:true}).fill('Received documents');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  const saved=await page.evaluate(()=>Object.entries(localStorage).filter(([key])=>key.startsWith('aadhar:views:')).map(([,v])=>JSON.parse(v)));
  expect(saved.flat().find(v=>v.name==='Received documents').filters.type).toBe('goods_receipt');
  expect(saved.flat().every(v=>Object.keys(v).every(k=>['name','filters'].includes(k)))).toBe(true);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true);
  await page.addScriptTag({path:'node_modules/axe-core/axe.min.js'});
  const violations=await page.evaluate(async()=>{const result=await window.axe.run(document.querySelector('#erp-main'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa']}});return result.violations.filter(v=>['serious','critical'].includes(v.impact)).map(v=>({id:v.id,description:v.description}));});
  expect(violations).toEqual([]);
  await page.screenshot({path:`.commerce-tmp/phase1g-explorer-${info.project.name}.png`,fullPage:true});
});

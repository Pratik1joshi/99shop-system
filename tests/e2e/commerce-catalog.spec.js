import { test, expect } from '@playwright/test';

const ADMIN_PIN = process.env.E2E_ADMIN_PIN || 'KmTestOnly123';

test('admin quick-creates a product, edits its SKU, and adds an alternate barcode', async ({ page }) => {
  test.setTimeout(120_000);
  const suffix = Date.now().toString().slice(-9);
  const name = `Catalog E2E ${suffix}`;
  const primary = `CAT${suffix}01`;
  const alternate = `CAT${suffix}02`;
  const sku = `CAT-SKU-${suffix}`;
  await page.goto('/login');
  await expect(page.getByText('Signing in as admin')).toBeVisible();
  await page.locator('#admin-pin').fill(ADMIN_PIN);
  await page.getByRole('button', { name: /^Sign in$/i }).click();
  await expect(page).toHaveURL(/\/admin\/dashboard/);
  await page.goto('/admin/products');
  await expect(page.getByRole('heading', { name: 'Products' })).toBeVisible();
  await page.getByRole('button', { name: 'Add product' }).click();
  const drawer = page.getByRole('dialog', { name: 'Add product' });
  await drawer.getByLabel('Name').fill(name);
  await drawer.getByLabel('Selling price').fill('125');
  await drawer.getByLabel('Barcode (optional)').fill(primary);
  await drawer.getByRole('button', { name: 'Save product' }).click();
  await expect(page.getByRole('dialog', { name })).toBeVisible();
  const detail = page.getByRole('dialog', { name });
  await detail.getByLabel('Brand').fill('Commerce Test');
  await detail.getByRole('button', { name: 'Add SKU / variant' }).click();
  const variant = detail.locator('fieldset').last();
  await variant.getByLabel('Variant').fill('Blue');
  await variant.getByLabel('SKU').fill(sku);
  await variant.getByLabel('Retail price').fill('140');
  await variant.getByLabel('MRP').fill('160');
  await variant.getByLabel('Wholesale price').fill('110');
  await variant.getByLabel('Reorder point').fill('8');
  await variant.getByLabel('Reorder quantity').fill('12');
  await variant.getByLabel('New attribute name').fill('Color');
  await variant.getByLabel('New attribute value').fill('Blue');
  await variant.getByRole('button', { name: 'Add attribute' }).click();
  await variant.getByLabel('Tracking').selectOption('batch');
  await detail.getByRole('button', { name: 'Save product' }).click();
  const saved = page.getByRole('dialog', { name });
  await expect(saved.getByRole('button', { name: 'Save product' })).toBeEnabled();
  const savedVariant = saved.locator('fieldset').last();
  await expect(savedVariant.getByLabel('Reorder quantity')).toHaveValue('12.00');
  await expect(savedVariant.getByLabel('Color')).toHaveValue('Blue');
  await savedVariant.getByLabel('SKU').fill(`${sku}-EDIT`);
  await saved.getByRole('button', { name: 'Save product' }).click();
  await expect(page.getByRole('dialog', { name }).locator('fieldset').last().getByLabel('SKU')).toHaveValue(`${sku}-EDIT`);
  await saved.getByRole('combobox', { name: 'SKU' }).selectOption({ label: `${sku}-EDIT` });
  await saved.getByLabel('Additional barcode').fill(alternate);
  await saved.getByRole('button', { name: 'Add barcode' }).click();
  await expect(saved.getByText(alternate)).toBeVisible();
  await saved.getByRole('button', { name: 'Close' }).click();
  await page.getByLabel('Find product / SKU / barcode').fill(alternate);
  await expect(page.getByRole('button', { name })).toBeVisible();
});
